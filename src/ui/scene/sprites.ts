export const SPRITE_W = 16
export const SPRITE_H = 12

const BLANK = '.'.repeat(SPRITE_W)

/** 그림 전체를 아래로 n칸 민다. 위쪽은 비운다. */
function down(rows: string[], n = 1): string[] {
  return [...Array(n).fill(BLANK), ...rows.slice(0, rows.length - n)]
}

/** 그림 전체를 위로 n칸 올린다. 아래쪽은 비운다. */
function up(rows: string[], n = 1): string[] {
  return [...rows.slice(n), ...Array(n).fill(BLANK)]
}

/** 특정 줄만 바꾼 새 그림 */
function patch(rows: string[], edits: Record<number, string>): string[] {
  return rows.map((r, i) => edits[i] ?? r)
}

